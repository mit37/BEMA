def cmd_bema(args):
    import torch
    from tokenizers import Tokenizer
    from model import JevCloneEncoder

    data = load_data()
    tok = Tokenizer.from_file("data/tokenizer_multitask.json")
    max_len, pad = data["max_len"], data["pad_id"]

    def enc(texts):
        ids, masks = [], []
        for t in texts:
            x = tok.encode(t).ids[:max_len]
            ids.append(x + [pad] * (max_len - len(x)))
            masks.append([1] * len(x) + [0] * (max_len - len(x)))
        return torch.tensor(ids), torch.tensor(masks)

    os.makedirs("runs/bema", exist_ok=True)
    timing = json.load(open("runs/bema/timing.json")) if os.path.exists("runs/bema/timing.json") else {}
    for name, path in CHECKPOINTS.items():
        m = JevCloneEncoder(vocab_size=data["vocab_size"], max_len=max_len,
                            num_choice_classes=data["num_choice_classes"], enable_score=True)
        m.load_state_dict(torch.load(path, map_location="cpu"))
        m.eval()
        for task, spec in TASKS.items():
            for cond in spec["conditions"]:
                rows = load_inputs(task, cond)
                ids, mask = enc([r["text"] for r in rows])
                out = []
                with torch.no_grad():
                    for i in range(0, len(rows), 256):
                        if spec["head"] == "choice":
                            _, conf, probs = m.predict_choice(ids[i:i + 256], mask[i:i + 256])
                            preds = probs.argmax(dim=-1).tolist()
                            out += [(p, c) for p, c in zip(preds, conf.tolist())]
                        else:
                            is_spam, conf, _ = m.predict(ids[i:i + 256], mask[i:i + 256])
                            out += [(int(p), c) for p, c in zip(is_spam.int().tolist(), conf.tolist())]
                with open(f"runs/bema/{name}_{task}_{cond}.jsonl", "w") as f:
                    for r, (p, c) in zip(rows, out):
                        f.write(json.dumps({"idx": r["idx"], "text_sha256": r["text_sha256"],
                                            "pred": p, "conf": c}) + "\n")
        # Single-example CPU latency on the first 300 clean BANKING77 queries.
        rows = load_inputs("banking77", "clean")[:300]
        lat = []
        with torch.no_grad():
            for r in rows[:20]:
                m.forward_all(*enc([r["text"]]))
            for r in rows:
                i, k = enc([r["text"]])
                t0 = time.perf_counter()
                m.forward_all(i, k)
                lat.append((time.perf_counter() - t0) * 1000)
        timing[name] = {"n": len(lat), "median_ms": statistics.median(lat),
                        "p90_ms": sorted(lat)[int(0.9 * len(lat))],
                        "threads": torch.get_num_threads(),
                        "note": "model forward pass only, batch size 1, CPU, excludes tokenization"}
        print(f"{name}: wrote predictions; median single-example latency {timing[name]['median_ms']:.2f} ms")
    with open("runs/bema/timing.json", "w") as f:
        json.dump(timing, f, indent=2)


