def ece(confs, correct):
    from calib_utils import ece as _ece
    return _ece(confs, correct)


def boot_ci(values, n_boot=2000, seed=0):
    """Percentile bootstrap 95% CI of the mean (resampling examples)."""
    import numpy as np
    arr = np.asarray(values, dtype=np.float64)
    rng = np.random.default_rng(seed)
    means = arr[rng.integers(0, len(arr), size=(n_boot, len(arr)))].mean(axis=1)
    lo, hi = np.percentile(means, [2.5, 97.5])
    return float(lo), float(hi)


def summarize(correct, confs):
    acc = sum(correct) / len(correct)
    mc = sum(confs) / len(confs)
    lo, hi = boot_ci(correct)
    return {"n": len(correct), "accuracy": acc, "accuracy_ci95": [lo, hi], "mean_confidence": mc,
            "overconfidence": mc - acc, "ece": ece(confs, correct)}


def cmd_report(args):
    report = {"generated_utc": datetime.now(timezone.utc).isoformat(), "mock": MOCK, "tasks": {}}
    man_path = f"{RUNS}/jev/manifest.json"
    report["jev_manifest"] = json.load(open(man_path)) if os.path.exists(man_path) else None
    all_lat, tokens_in, versions, n_err = [], 0, {}, 0

    for task, spec in TASKS.items():
        report["tasks"][task] = {}
        for cond in spec["conditions"]:
            inputs = load_inputs(task, cond)
            by_idx = {r["idx"]: r for r in inputs}
            res = {}
            # Jev: last ok record per idx; check it answered the exact text we sent.
            jev = {}
            for rec in read_jsonl(f"{RUNS}/jev/{task}_{cond}.jsonl"):
                if rec["status"] == "ok":
                    if rec["text_sha256"] != by_idx[rec["idx"]]["text_sha256"]:
                        sys.exit(f"Text hash mismatch in {task}/{cond} idx {rec['idx']}: inputs changed after the Jev run.")
                    jev[rec["idx"]] = rec
            errors = len({r["idx"] for r in read_jsonl(f"{RUNS}/jev/{task}_{cond}.jsonl")} - set(jev))
            n_err += errors
            if jev:
                c, conf, own = [], [], []
                for idx in sorted(jev):
                    rec = jev[idx]
                    pred, cf, jc = parse_answer(task, rec["response"])
                    c.append(1.0 if pred == gold(task, by_idx[idx]["label"]) else 0.0)
                    conf.append(cf)
                    own.append(jc)
                    all_lat.append(rec["latency_ms"])
                    tokens_in += rec["response"].get("usage", {}).get("input_tokens", 0) or 0
                    v = rec["response"].get("model", "unreported")
                    versions[v] = versions.get(v, 0) + 1
                res["jev"] = summarize(c, conf)
                res["jev"]["n_failed_calls"] = errors
                res["jev"]["n_missing"] = len(inputs) - len(jev)
                if all(x is not None for x in own):
                    res["jev"]["ece_using_jev_confidence_field"] = ece(own, c)
                jev_correct = dict(zip(sorted(jev), c))
            for name in REPORT_MODELS:
                rows = read_jsonl(f"runs/bema/{name}_{task}_{cond}.jsonl")
                if not rows:
                    continue
                for r in rows:
                    if r["text_sha256"] != by_idx[r["idx"]]["text_sha256"]:
                        sys.exit(f"Text hash mismatch for {name} {task}/{cond} idx {r['idx']}.")
                cats = categories()
                def ok(r):
                    p = cats[r["pred"]] if task == "banking77" else r["pred"]
                    return 1.0 if p == gold(task, by_idx[r["idx"]]["label"]) else 0.0
                res[name] = summarize([ok(r) for r in rows], [r["conf"] for r in rows])
                if jev:  # paired on exactly the examples Jev answered
                    bema_c = {r["idx"]: ok(r) for r in rows}
                    diffs = [jev_correct[i] - bema_c[i] for i in sorted(jev_correct)]
                    lo, hi = boot_ci(diffs)
                    res[f"jev_minus_{name}_accuracy"] = {"n": len(diffs), "diff": sum(diffs) / len(diffs),
                                                         "ci95": [lo, hi]}
            report["tasks"][task][cond] = res

    for task, conds in report["tasks"].items():   # drop from clean, per model
        clean = conds.get("clean", {})
        for cond, res in conds.items():
            if cond == "clean":
                continue
            for model in ("jev", *REPORT_MODELS):
                if model in res and model in clean:
                    res[model]["accuracy_drop_from_clean"] = clean[model]["accuracy"] - res[model]["accuracy"]
                    res[model]["confidence_drop_from_clean"] = clean[model]["mean_confidence"] - res[model]["mean_confidence"]

    if all_lat:
        s = sorted(all_lat)
        report["jev_latency_ms"] = {"n": len(s), "median": statistics.median(s),
                                    "p90": s[int(0.9 * len(s))], "p99": s[int(0.99 * len(s))]}
        report["jev_cost"] = {"input_tokens": tokens_in,
                              "usd": tokens_in / 1e6 * PRICE_PER_M_INPUT, "price_source": PRICE_SOURCE}
        report["jev_model_versions_reported"] = versions
        report["jev_failed_calls_total"] = n_err
    if os.path.exists("runs/bema/timing.json"):
        report["bema_latency"] = json.load(open("runs/bema/timing.json"))

    # Cross-check against the repo's own script on identical text.
    if os.path.exists("heldout_noise_results.pkl"):
        ref = pickle.load(open("heldout_noise_results.pkl", "rb"))["results"]
        mapping = {"baseline": "bema_baseline", "augmented": "bema_typo_augmented"}
        mism = []
        for (m, c), v in ref.items():
            ours = report["tasks"]["banking77"].get(c, {}).get(mapping[m])
            if ours and (abs(ours["accuracy"] - v["acc"]) > 1e-9 or abs(ours["ece"] - v["ece"]) > 1e-6):
                mism.append((m, c, v["acc"], ours["accuracy"]))
        report["crosscheck_vs_heldout_noise_test"] = "match" if not mism else mism

    os.makedirs(RUNS, exist_ok=True)
    with open(f"{RUNS}/report.json", "w") as f:
        json.dump(report, f, indent=2)
    write_markdown(report)
    print(f"Wrote {RUNS}/report.json and {RUNS}/REPORT.md")


def write_markdown(rep):
    L = ["# Jev vs BEMA: generated results", "",
         f"Generated {rep['generated_utc']} by `python3 bench_jev.py report` from the raw files in "
         f"`{RUNS}/`. Nothing in this file is typed by hand." + (" **MOCK RUN: not real Jev output.**" if rep["mock"] else ""), ""]
    if rep.get("jev_model_versions_reported"):
        L.append(f"Jev model version(s) reported by the API: {rep['jev_model_versions_reported']}")
    if rep.get("crosscheck_vs_heldout_noise_test"):
        L.append(f"BEMA cross-check against `heldout_noise_test.py` on identical text: {rep['crosscheck_vs_heldout_noise_test']}")
    L.append("")
    for task, conds in rep["tasks"].items():
        L += [f"## {task}", "",
              "| condition | model | n | accuracy (95% CI) | mean conf | overconf | ECE | acc drop | conf drop |",
              "|---|---|---|---|---|---|---|---|---|"]
        for cond, res in conds.items():
            for model in ("jev", *REPORT_MODELS):
                if model not in res:
                    continue
                r = res[model]
                drop = f"{r['accuracy_drop_from_clean']:+.3f}" if "accuracy_drop_from_clean" in r else ""
                cdrop = f"{r['confidence_drop_from_clean']:+.3f}" if "confidence_drop_from_clean" in r else ""
                L.append(f"| {cond}{' (held out)' if cond in HELD_OUT else ''} | {model} | {r['n']} | "
                         f"{r['accuracy']:.3f} ({r['accuracy_ci95'][0]:.3f}-{r['accuracy_ci95'][1]:.3f}) | "
                         f"{r['mean_confidence']:.3f} | {r['overconfidence']:+.3f} | {r['ece']:.4f} | {drop} | {cdrop} |")
        L.append("")
    for k in ("jev_latency_ms", "jev_cost", "bema_latency"):
        if rep.get(k):
            L += [f"**{k}**: `{json.dumps(rep[k])}`", ""]
    L += ["Held out = a typo type the typo-augmented BEMA never saw in training (it was trained on swap2 only).",
          "Jev answers zero-shot from category names; BEMA was trained on this task. Compare each model's "
          "drop from clean, not raw accuracy across models."]
    with open(f"{RUNS}/REPORT.md", "w") as f:
        f.write("\n".join(L) + "\n")


