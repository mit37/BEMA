"""
Head-to-head benchmark: Jev (TypeSafe's System One model, called through its
real HTTP API) vs BEMA, on the SAME held-out test examples, clean and with
typos.

Every number this produces is recomputed from raw per-example files, so any
figure can be traced back to the exact API response or model output behind it:

  runs/inputs/<task>_<cond>.jsonl   the exact text + gold label each model saw
  runs/jev/<task>_<cond>.jsonl      one line per Jev call: raw JSON response,
                                    latency, attempts, HTTP status
  runs/bema/<ckpt>_<task>_<cond>.jsonl  one line per BEMA prediction
  runs/jev/manifest.json            questions, instructions, model, endpoint,
                                    price used for cost (never the API key)
  runs/report.json, runs/REPORT.md  generated by `report`, nothing typed by hand

Subcommands (run in this order):
  python3 bench_jev.py prepare        # write the shared inputs (no key needed)
  python3 bench_jev.py models         # list the models this key can see
  python3 bench_jev.py smoke          # 3 real calls per task, prints raw JSON
  python3 bench_jev.py jev [--limit N] [--tasks ...] [--conditions ...]
  python3 bench_jev.py bema           # both BEMA checkpoints on identical text
  python3 bench_jev.py report         # recompute every metric from raw files

Environment:
  JEV_API_KEY      required for models/smoke/jev. Read from the environment
                   only; never printed, logged or written to disk.
  JEV_BASE_URL     default https://api.typesafe.ai
  JEV_MODEL        default jev-latest. The version Jev reports back in each
                   response is what the report cites, not this alias.
  JEV_CONCURRENCY  default 8
  JEV_MOCK=1       fake in-process Jev for dry runs; writes under runs/mock/
                   so mock output can never mix with real results.

Typo noise is generated exactly the way heldout_noise_test.py does it (noise.py
operations, random.Random(f"99-{name}") per noise type, applied over the test
split in order), so on BANKING77 the BEMA numbers here must match that
script's output. `report` checks this when heldout_noise_results.pkl exists.

What this comparison is and is not: Jev answers zero-shot. It sees only the
77 BANKING77 category names (as written in the dataset, underscores turned
into spaces) and the SMS text. BEMA was trained on 8,503 labelled BANKING77
training examples and 3,900 labelled SMS messages. A raw accuracy gap therefore mostly
measures "trained on this task" vs "not trained on it". The like-for-like
question is each model's own drop from clean to typo'd input, and whether its
confidence falls as much as its accuracy does.
"""
