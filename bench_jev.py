def question_spec(task):
    if task == "banking77":
        return {"intent": {
            "type": "choice",
            "instructions": "Which banking customer-support intent does this customer message express?",
            "criteria": {c: c.replace("_", " ") for c in categories()},
        }}
    return {"is_spam": {
        "type": "noul",
        "instructions": "This SMS message is spam.",
    }}


def parse_answer(task, response):
    """Return (predicted label, confidence = probability of the predicted
    answer, Jev's own `confidence` field or None). Raises if the response
    does not have the documented shape, so a schema surprise fails loudly
    instead of being silently scored as wrong."""
    answers = response["answers"]
    if task == "banking77":
        a = answers["intent"]
        probs = a.get("probabilities") or {}
        pred = a.get("choice") or max(probs, key=probs.get)
        conf = float(probs[pred]) if pred in probs else float(a["confidence"])
        return pred, conf, (float(a["confidence"]) if a.get("confidence") is not None else None)
    a = answers["is_spam"]
    p = a["noul"] if isinstance(a, dict) else a
    p = float(p["probability"] if isinstance(p, dict) else p)
    pred = 1 if p > 0.5 else 0
    return pred, (p if pred == 1 else 1 - p), None


def gold(task, label):
    return categories()[label] if task == "banking77" else int(label)


def mock_transport():
    import httpx

    async def handler(request):
        await asyncio.sleep(random.uniform(0.005, 0.02))
        if request.url.path.endswith("/models"):
            return httpx.Response(200, json={"data": [{"id": "mock-jev-0.0"}]})
        body = json.loads(request.content)
        answers = {}
        for name, q in body["questions"].items():
            if q["type"] == "choice":
                opts = list(q["criteria"])
                w = [random.random() ** 4 for _ in opts]
                s = sum(w)
                probs = {o: x / s for o, x in zip(opts, w)}
                best = max(probs, key=probs.get)
                answers[name] = {"type": "choice", "choice": best, "probabilities": probs,
                                 "confidence": probs[best]}
            elif q["type"] == "score":
                w = [random.random() ** 4 for _ in q["criteria"]]
                probs = {str(i): x / sum(w) for i, x in enumerate(w)}
                answers[name] = {"type": "score", "score": sum(int(k) * v for k, v in probs.items()),
                                 "confidence": max(probs.values()), "probabilities": probs,
                                 "legend": {str(i): c for i, c in enumerate(q["criteria"])}}
            else:
                answers[name] = {"type": "noul", "noul": random.random()}
        if random.random() < 0.02:
            return httpx.Response(429, headers={"retry-after": "0"}, json={"detail": "mock rate limit"})
        return httpx.Response(200, json={"model": "mock-jev-0.0", "answers": answers,
                                         "usage": {"input_tokens": 400, "output_tokens": 0}})
    return httpx.MockTransport(handler)


def client():
    import httpx
    key = os.environ.get("JEV_API_KEY", "")
    if not key and not MOCK:
        sys.exit("JEV_API_KEY is not set.")
    base = os.environ.get("JEV_BASE_URL", "https://api.typesafe.ai").rstrip("/")
    kwargs = {"base_url": base, "timeout": httpx.Timeout(60.0),
              "headers": {"Authorization": f"Bearer {key or 'mock'}", "Content-Type": "application/json"}}
    if MOCK:
        kwargs["transport"] = mock_transport()
    return httpx.AsyncClient(**kwargs)


def model_name():
    return os.environ.get("JEV_MODEL", "jev-latest")


def jev_body(task, text, questions=None):
    return {"model": model_name(), "state": text, "questions": questions or question_spec(task)}


async def call_jev(c, body, max_attempts=6):
    attempt, last = 0, None
    while attempt < max_attempts:
        attempt += 1
        t0 = time.perf_counter()
        try:
            r = await c.post("/v1/systemone", json=body)
        except Exception as e:  # network error / timeout
            last = {"http_status": None, "error": f"{type(e).__name__}: {e}"}
            await asyncio.sleep(min(30, 2 ** attempt) * random.uniform(0.5, 1.0))
            continue
        latency_ms = (time.perf_counter() - t0) * 1000
        if r.status_code == 200:
            return {"status": "ok", "http_status": 200, "latency_ms": latency_ms,
                    "attempts": attempt, "response": r.json()}
        last = {"http_status": r.status_code, "error": r.text[:500]}
        if r.status_code in (429, 500, 502, 503, 504):
            wait = r.headers.get("retry-after")
            delay = float(wait) if wait and wait.replace(".", "", 1).isdigit() else min(30, 2 ** attempt)
            await asyncio.sleep(delay * random.uniform(0.8, 1.2))
            continue
        break  # 4xx other than 429: retrying will not help
    return {"status": "error", "attempts": attempt, **(last or {})}


BUDGET_USD = float(os.environ.get("JEV_BUDGET_USD", "4.50"))
DEFAULT_TOKENS = {"banking77": 1700, "spam": 330}


def spent_usd():
    """Input tokens actually reported by Jev across every raw file, priced."""
    import glob
    tok = 0
    for path in glob.glob(f"{RUNS}/**/*.jsonl", recursive=True):
        if not MOCK and path.startswith("runs/mock/"):
            continue   # mock runs live under runs/mock; never count them as real spend
        for r in read_jsonl(path):
            if r.get("status") == "ok":
                tok += (r.get("response") or {}).get("usage", {}).get("input_tokens", 0) or 0
    return tok / 1e6 * PRICE_PER_M_INPUT


def avg_tokens(path, fallback):
    toks = [r["response"]["usage"]["input_tokens"] for r in read_jsonl(path)
            if r.get("status") == "ok" and r.get("response", {}).get("usage")]
    return sum(toks) / len(toks) if toks else fallback


def check_budget(n_calls, tokens_per_call, label):
    spent = spent_usd()
    projected = n_calls * tokens_per_call / 1e6 * PRICE_PER_M_INPUT
    print(f"  budget: spent ${spent:.3f}, this step ~${projected:.3f}, cap ${BUDGET_USD:.2f}", flush=True)
    if spent + projected > BUDGET_USD:
        sys.exit(f"STOP: {label} would take spend to ~${spent + projected:.2f}, over the "
                 f"${BUDGET_USD:.2f} cap. Nothing was called for this step.")


def manifest():
    return {
        "endpoint": os.environ.get("JEV_BASE_URL", "https://api.typesafe.ai").rstrip("/") + "/v1/systemone",
        "model_requested": model_name(),
        "questions": {t: question_spec(t) for t in TASKS},
        "noise_seed": SEED,
        "price_per_million_input_tokens_usd": PRICE_PER_M_INPUT,
        "price_source": PRICE_SOURCE,
        "client_location_note": "Calls made from an Anthropic cloud workspace; latency is client-side "
                                "wall clock and includes the network round trip.",
        "mock": MOCK,
    }


def check_manifest():
    os.makedirs(f"{RUNS}/jev", exist_ok=True)
    path = f"{RUNS}/jev/manifest.json"
    m = manifest()
    if os.path.exists(path):
        with open(path) as f:
            old = json.load(f)
        keys = ("endpoint", "model_requested", "questions", "noise_seed")
        if any(old.get(k) != m.get(k) for k in keys):
            sys.exit(f"{path} was written with different questions/model/endpoint. Results from two "
                     f"different setups must not be mixed: move {RUNS}/jev aside before re-running.")
        m["started_utc"] = old.get("started_utc")
    else:
        m["started_utc"] = datetime.now(timezone.utc).isoformat()
    with open(path, "w") as f:
        json.dump(m, f, indent=2)


async def run_jev(args):
    check_manifest()
    sem = asyncio.Semaphore(int(os.environ.get("JEV_CONCURRENCY", "8")))
    tasks = args.tasks or list(TASKS)
    async with client() as c:
        for task in tasks:
            for cond in TASKS[task]["conditions"]:
                if args.conditions and cond not in args.conditions:
                    continue
                rows = load_inputs(task, cond)[: args.limit or None]
                path = f"{RUNS}/jev/{task}_{cond}.jsonl"
                done = {r["idx"] for r in read_jsonl(path) if r["status"] == "ok"}
                todo = [r for r in rows if r["idx"] not in done]
                print(f"{task}/{cond}: {len(done)} cached, {len(todo)} to call", flush=True)
                if not todo:
                    continue
                check_budget(len(todo), avg_tokens(path, DEFAULT_TOKENS[task]), f"{task}/{cond}")
                lock, counter = asyncio.Lock(), {"n": 0, "err": 0}

                async def one(row, f):
                    async with sem:
                        rec = await call_jev(c, jev_body(task, row["text"]))
                    rec.update({"idx": row["idx"], "text_sha256": row["text_sha256"],
                                "ts_utc": datetime.now(timezone.utc).isoformat()})
                    async with lock:
                        f.write(json.dumps(rec) + "\n")
                        f.flush()
                        counter["n"] += 1
                        counter["err"] += rec["status"] != "ok"
                        if counter["n"] % 250 == 0:
                            print(f"  {counter['n']}/{len(todo)} (errors so far: {counter['err']})", flush=True)

                with open(path, "a", encoding="utf-8") as f:
                    await asyncio.gather(*(one(r, f) for r in todo))
                print(f"  finished {task}/{cond}: {counter['n']} calls, {counter['err']} errors", flush=True)


