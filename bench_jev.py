                print(json.dumps({k: v for k, v in rec.items() if k != "response"}))
                if rec["status"] == "ok":
                    resp = rec["response"]
                    shown = json.loads(json.dumps(resp))
                    for a in shown.get("answers", {}).values():   # trim 77-way probability dicts
                        if isinstance(a, dict) and isinstance(a.get("probabilities"), dict):
                            n_opts = len(a["probabilities"])
                            top = sorted(a["probabilities"].items(), key=lambda kv: -kv[1])[:3]
                            a["probabilities"] = {**dict(top), "...": f"top 3 of {n_opts} options shown"}
                    print(json.dumps(shown, indent=2)[:1500])
                    print("parsed (pred, conf, jev_confidence):", parse_answer(task, resp))


